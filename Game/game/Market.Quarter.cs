using System;
using System.Collections.Generic;

namespace SpaceAge
{
	public partial class Market
	{
		public static void GenerateOffers()
		{
			if (TurnGmLog.Current != null && TurnGmLog.Current.IsEnabled(ETurnGmLogChannel.Market))
			{
				TurnGmLog.Current.AppendSection("market autogenerated offers");
			}
			RefillSettlementBuyOffers();

			foreach (ModuleStack stack in ModuleStack.All.Values)
			{
				if (stack.Owner == null || stack.Owner.Name != "1")
				{
					continue;
				}
				if (stack.ModuleType == null || stack.ModuleType.Name != "city")
				{
					continue;
				}

				foreach (ItemStack items in stack.ItemStacks.Values)
				{
					if (items == null || items.Quantity <= 0)
					{
						continue;
					}
					if (items.ItemType == ItemType.All.Cash)
					{
						continue;
					}
					if (hasItemOffer(stack, EOfferType.BuyItems, items.ItemType)
						|| hasItemOffer(stack, EOfferType.SellItems, items.ItemType))
					{
						continue;
					}

					int price = (int)stack.Location.Market.GetPrice(items.ItemType);
					if (price <= 0)
					{
						continue;
					}

					Offer offer = new Offer(stack.Location.Market, stack, EOfferType.SellItems);
					offer.ItemType = items.ItemType;
					offer.Quantity = items.Quantity;
					offer.Price = price;
					Offer stored = Offer.All.ReuseEquivalent(offer);
					logAutogeneratedOffer(stack.Location as Region, stored, offer, "create");
				}
			}
			if (TurnGmLog.Current != null && TurnGmLog.Current.IsEnabled(ETurnGmLogChannel.Market))
			{
				TurnGmLog.Current.Append(string.Empty);
			}
		}

		public static void UpdateRates()
		{
			TurnGmLog log = TurnGmLog.Current;
			bool logMarket = log != null && log.IsEnabled(ETurnGmLogChannel.Market);
			Dictionary<string, Dictionary<string, double>> priceSnapshot = logMarket
				? snapshotMarketPrices()
				: null;
			updateMarketPrices();
			if (logMarket)
			{
				logMarketPriceChanges(priceSnapshot, "offer-pressure-drift");
				priceSnapshot = snapshotMarketPrices();
			}
			updateRegionalAveragePrices();
			if (logMarket)
			{
				logMarketPriceChanges(priceSnapshot, "regional-average");
			}
			updateBankRates();
		}

		private static void RefillSettlementBuyOffers()
		{
			foreach (ModuleStack stack in ModuleStack.All.Values)
			{
				if (!isNpcSettlementMarket(stack))
				{
					continue;
				}

				foreach (SettlementBuyTarget target in SettlementBuyBook.Targets(stack.ModuleType.Name, stack.Quantity))
				{
					refillSettlementBuyOffer(stack, target);
				}
			}
		}

		private static bool isNpcSettlementMarket(ModuleStack stack)
		{
			if (stack.Owner == null || stack.Owner.Name != "1")
			{
				return false;
			}
			if (stack.ModuleType == null || stack.ModuleType.Group != EModuleTypesGroup.settlement)
			{
				return false;
			}
			string name = stack.ModuleType.Name;
			return name == "town" || name == "city" || name == "mtrply";
		}

		private static void refillSettlementBuyOffer(ModuleStack stack, SettlementBuyTarget target)
		{
			Offer existing = target.IsModule
				? findModuleBuyOffer(stack, target.ModuleType)
				: findItemBuyOffer(stack, target.ItemType);

			if (existing != null)
			{
				if (existing.Quantity < target.Quantity)
				{
					int oldQuantity = existing.Quantity;
					existing.Quantity = target.Quantity;
					if (oldQuantity != existing.Quantity)
					{
						logAutogeneratedOffer(stack.Location as Region, existing, null, "refill");
					}
				}
				return;
			}

			EOfferType offerType = target.IsModule ? EOfferType.BuyModules : EOfferType.BuyItems;
			Offer offer = new Offer(stack.Location.Market, stack, offerType);
			if (target.IsModule)
			{
				offer.ModuleType = target.ModuleType;
			}
			else
			{
				offer.ItemType = target.ItemType;
			}
			offer.Quantity = target.Quantity;
			offer.Price = target.Price;
			Offer stored = Offer.All.ReuseEquivalent(offer);
			logAutogeneratedOffer(stack.Location as Region, stored, offer, "create");
		}

		private static void logAutogeneratedOffer(Region region, Offer stored, Offer candidate, string action)
		{
			TurnGmLog log = TurnGmLog.Current;
			if (log == null || !log.IsEnabled(ETurnGmLogChannel.Market) || region == null || stored == null)
			{
				return;
			}
			if (candidate != null && !object.ReferenceEquals(stored, candidate))
			{
				return;
			}
			log.LogMarketOffer(region, action, stored);
		}

		private static Offer findItemBuyOffer(ModuleStack stack, ItemType itemType)
		{
			foreach (Offer offer in Offer.All[stack])
			{
				if (offer.OfferType == EOfferType.BuyItems && offer.ItemType == itemType)
				{
					return offer;
				}
			}
			return null;
		}

		private static Offer findModuleBuyOffer(ModuleStack stack, ModuleType moduleType)
		{
			foreach (Offer offer in Offer.All[stack])
			{
				if (offer.OfferType == EOfferType.BuyModules && offer.ModuleType == moduleType)
				{
					return offer;
				}
			}
			return null;
		}

		private static bool hasItemOffer(ModuleStack stack, EOfferType offerType, ItemType itemType)
		{
			foreach (Offer offer in Offer.All[stack])
			{
				if (offer.OfferType == offerType && offer.ItemType == itemType)
				{
					return true;
				}
			}
			return false;
		}

		private static void updateMarketPrices()
		{
			foreach (Region region in Region.All.Values)
			{
				region.Market.ApplyOfferPressureDrift();
			}
		}

		private static void updateRegionalAveragePrices()
		{
			foreach (Region region in Region.All.Values)
			{
				foreach (ItemType itemType in ItemType.All.Values)
				{
					if (!region.Market.PriceList.ContainsKey(itemType))
					{
						continue;
					}

					double sum = 0;
					int count = 0;
					foreach (Region other in Region.All.Values)
					{
						if (other.Market.PriceList.ContainsKey(itemType))
						{
							sum += other.Market.PriceList[itemType];
							count++;
						}
					}

					if (count == 0)
					{
						continue;
					}

					double averageRaw = sum / count;
					int average = (int)Math.Round(averageRaw, MidpointRounding.AwayFromZero);
					if (average < 1 && averageRaw >= 0.5)
					{
						average = 1;
					}

					region.Market.AddPrice(itemType, average);
				}
			}
		}

		private static Dictionary<string, Dictionary<string, double>> snapshotMarketPrices()
		{
			Dictionary<string, Dictionary<string, double>> snapshot = new Dictionary<string, Dictionary<string, double>>();
			foreach (Region region in Region.All.Values)
			{
				Dictionary<string, double> prices = new Dictionary<string, double>();
				foreach (KeyValuePair<NamedType, double> entry in region.Market.PriceList)
				{
					prices[entry.Key.Name] = entry.Value;
				}
				snapshot[region.Name] = prices;
			}
			return snapshot;
		}

		private static void logMarketPriceChanges(Dictionary<string, Dictionary<string, double>> before, string reason)
		{
			TurnGmLog log = TurnGmLog.Current;
			if (log == null || !log.IsEnabled(ETurnGmLogChannel.Market))
			{
				return;
			}
			bool wroteSection = false;
			foreach (Region region in Region.All.Values)
			{
				Dictionary<string, double> oldPrices;
				if (!before.TryGetValue(region.Name, out oldPrices))
				{
					oldPrices = new Dictionary<string, double>();
				}
				foreach (KeyValuePair<NamedType, double> entry in region.Market.PriceList)
				{
					double oldPrice;
					if (!oldPrices.TryGetValue(entry.Key.Name, out oldPrice))
					{
						oldPrice = entry.Value;
					}
					if (Math.Abs(oldPrice - entry.Value) < 0.001)
					{
						continue;
					}
					if (!wroteSection)
					{
						log.AppendSection(string.Format("market price changes ({0})", reason));
						wroteSection = true;
					}
					log.LogMarketPriceChange(region, entry.Key, oldPrice, entry.Value, reason);
				}
			}
			if (wroteSection)
			{
				log.Append(string.Empty);
			}
		}

		private static void updateBankRates()
		{
			foreach (Faction faction in Faction.All.Values)
			{
				int factionId;
				if (!int.TryParse(faction.Name, out factionId) || factionId < 2 || factionId > 11)
				{
					continue;
				}

				if (faction.Bank.Balance > 5000)
				{
					faction.Bank.DepositRate = Math.Max(0.01, faction.Bank.DepositRate - 0.005);
				}

				if (faction.Bank.Balance < 0)
				{
					faction.Bank.CreditRate = Math.Min(0.25, faction.Bank.CreditRate + 0.005);
				}
			}
		}
	}
}
